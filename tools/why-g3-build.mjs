// `node tools/why-g3-build.mjs [cat…]` — builds js/content/why/g3-<cat>.js (grade-3 topics of « Pourquoi? ») from the plain-text
// sources tools/why-g3/<cat>.mjs, where every zh is a plain string; pinyin + word lengths come from tools/why-pinyin.py.
import fs from 'node:fs';
import { spawnSync } from 'node:child_process';
const root = new URL('../', import.meta.url);
const CATS = ['animaux', 'corps', 'ciel', 'terre', 'science', 'techno'];
const only = process.argv.slice(2);
const py = new URL('localvoice/.venv/Scripts/python.exe', root).pathname.replace(/^\//, '');
for (const cat of CATS) {
  if (only.length && !only.includes(cat)) continue;
  const f = new URL(`tools/why-g3/${cat}.mjs`, root);
  if (!fs.existsSync(f)) continue;
  const { topics } = await import(f.href + '?' + Date.now());
  const strs = new Set();
  const grab = (z) => { if (typeof z !== 'string') throw new Error('zh must be a plain string: ' + JSON.stringify(z)); strs.add(z); };
  for (const t of topics) {
    grab(t.q.zh);
    for (const s of t.slides) { if (s.words) s.words.forEach((w) => { grab(w.zh.t); grab(w.zh.d); }); else grab(s.zh); }
    for (const q of t.quiz) { grab(q.zh); q.options.forEach((o) => grab(o.zh)); }
  }
  const r = spawnSync(py, ['-I', '-X', 'utf8', 'tools/why-pinyin.py'], { input: JSON.stringify([...strs]), cwd: new URL('.', root).pathname.replace(/^\//, ''), encoding: 'utf8', maxBuffer: 1 << 28 });
  if (r.status !== 0) throw new Error(r.stderr);
  const map = JSON.parse(r.stdout);
  const Z = (s) => ({ hz: s, py: map[s].py, w: map[s].w });
  const out = topics.map((t) => ({
    id: t.id, cat, shelf: 'g3', grade: 3, emoji: t.emoji, level: t.level,
    q: { fr: t.q.fr, en: t.q.en, zh: Z(t.q.zh) },
    slides: t.slides.map((s) => s.words
      ? { kind: 'words', emoji: s.emoji, words: s.words.map((w) => ({ fr: w.fr, en: w.en, zh: { t: Z(w.zh.t), d: Z(w.zh.d) } })) }
      : { kind: s.kind, emoji: s.emoji, fr: s.fr, en: s.en, zh: Z(s.zh) }),
    quiz: t.quiz.map((q) => ({ fr: q.fr, en: q.en, zh: Z(q.zh), options: q.options.map((o) => ({ fr: o.fr, en: o.en, zh: Z(o.zh), emoji: o.emoji })), answer: q.answer })),
  }));
  const body = out.map((t) => '  ' + JSON.stringify(t)).join(',\n');
  fs.writeFileSync(new URL(`js/content/why/g3-${cat}.js`, root), `// Pourquoi? 十万个为什么 — 3e année (grade 3) topics, ${cat}. GENERATED by tools/why-g3-build.mjs from tools/why-g3/${cat}.mjs — edit the source, not this file.\nexport const topics = [\n${body},\n];\n`);
  console.log(cat, out.length, 'topics ->', `js/content/why/g3-${cat}.js`);
}
